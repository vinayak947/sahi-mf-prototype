export const cutoffKind = (fund: Fund): "liquid" | "other" => (fund.cat === "liquid" ? "liquid" : "other");

// Working days from the trade day until redemption money reaches the bank (AMFI norms):
// liquid and debt T+1, equity T+2, fund of funds (gold, silver) about T+4.
export const payoutDays = (fund: Fund): number =>
  fund.cat === "liquid" || fund.cat === "debt" ? 1 : fund.cat === "gold" ? 4 : 2;

